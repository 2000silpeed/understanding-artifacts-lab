"""Writes films/fenwick-20261022/facts.json — every number the film draws, computed by the example's own Fenwick class.

film.js imports facts.json (never its own arithmetic for the shown values); test_source.py checks facts.json against
examples/out/python.txt (the real run) and against the numbers in script.py.

usage: python3 films/fenwick-20261022/examples/facts.py
"""
import json
from pathlib import Path

from fenwick import Fenwick, bits, lowbit

HERE = Path(__file__).resolve().parent


def build():
    A = [3, 1, 4, 1, 5, 9, 2, 6]
    n = len(A)
    fw = Fenwick(n)
    for i, v in enumerate(A, 1):
        fw.update(i, v)
    tree0 = fw.tree[1:]
    covers = {i: [i - lowbit(i) + 1, i] for i in range(1, n + 1)}
    qpath = []
    q7 = fw.prefix(7, qpath)
    qsteps = [{'i': i, 'bin': bits(i, 4), 'low': lowbit(i), 'value': fw.tree[i]} for i in qpath]
    qrun, acc = [], 0
    for st in qsteps:
        acc += st['value']
        qrun.append(acc)
    prefix_before = [sum(A[:i]) for i in range(1, n + 1)]
    A2 = A[:]
    A2[2] += 5
    prefix_after = [sum(A2[:i]) for i in range(1, n + 1)]
    upath = []
    before = fw.tree[:]
    fw.update(3, 5, upath)
    usteps = [{'i': i, 'bin': bits(i, 4), 'low': lowbit(i), 'from': before[i], 'to': fw.tree[i]} for i in upath]
    unext = upath[-1] + lowbit(upath[-1])
    p7, p2 = fw.prefix(7), fw.prefix(2)
    big = 1_000_000
    return {
        '$doc': 'Generated by examples/facts.py from the Fenwick class in examples/fenwick.py. Do not edit by hand.',
        'A': A, 'n': n, 'tree': tree0, 'covers': covers,
        'naive': {'cellsRead': 7, 'sum7': sum(A[:7])},
        'query': {'to': 7, 'steps': qsteps, 'running': qrun, 'sum': q7, 'end': {'i': 0, 'bin': bits(0, 4)}},
        'update': {'at': 3, 'delta': 5, 'old': A[2], 'new': A2[2], 'steps': usteps, 'next': unext, 'nextBin': bits(unext, 5),
                   'A': A2, 'tree': fw.tree[1:]},
        'prefixTable': {'before': prefix_before, 'after': prefix_after,
                        'changed': [i + 1 for i in range(n) if prefix_before[i] != prefix_after[i]]},
        'range': {'l': 3, 'r': 7, 'prefixR': p7, 'prefixL1': p2, 'sum': fw.range_sum(3, 7)},
        'lowbit': {'i': 6, 'bin': bits(6, 8), 'flip': bits(~6, 8), 'neg': bits(-6, 8), 'and': bits(6 & -6, 8), 'value': 6 & -6},
        'big': {'n': big, 'bitLength': big.bit_length(), **steps(big)},
    }


def steps(N):
    mp = mu = 0
    for i in range(1, N + 1):
        c, j = 0, i
        while j > 0:
            c += 1
            j -= j & -j
        mp = max(mp, c)
        c, j = 0, i
        while j <= N:
            c += 1
            j += j & -j
        mu = max(mu, c)
    return {'maxPrefixSteps': mp, 'maxUpdateSteps': mu}


if __name__ == '__main__':
    out = HERE.parent / 'facts.json'
    out.write_text(json.dumps(build(), ensure_ascii=False, indent=1) + '\n')
    print('wrote', out)
